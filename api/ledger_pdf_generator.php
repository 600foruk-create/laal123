class LedgerPDF extends FPDF {
    public $companyName = 'SOFTIFYX ERP';
    public $companyAddress = '';
    public $companyPhone = '';
    public $accountName = '';
    public $accountCode = '';
    public $accountType = 'CUSTOMER';
    public $periodText = 'All Dates (Complete Ledger)';

    function Header() {
        // Company Title
        $this->SetFont('Arial', 'B', 15);
        $this->SetTextColor(31, 78, 121);
        $this->Cell(0, 7, $this->companyName, 0, 1, 'C');

        if (!empty($this->companyAddress)) {
            $this->SetFont('Arial', '', 8.5);
            $this->SetTextColor(100, 116, 139);
            $this->Cell(0, 4, $this->companyAddress, 0, 1, 'C');
        }

        $this->SetFont('Arial', 'B', 12);
        $this->SetTextColor(30, 41, 59);
        $this->Ln(2);
        $this->Cell(0, 6, "ACCOUNTS' GENERAL LEDGER STATEMENT", 0, 1, 'C');
        $this->SetDrawColor(31, 78, 121);
        $this->SetLineWidth(0.6);
        $this->Line(10, $this->GetY() + 1, 200, $this->GetY() + 1);
        $this->Ln(3);

        // Account Meta Info Box
        $this->SetFont('Arial', 'B', 8.5);
        $this->SetTextColor(30, 41, 59);

        $this->Cell(25, 5.5, 'Account Code:', 0, 0, 'L');
        $this->SetFont('Arial', '', 8.5);
        $this->Cell(65, 5.5, $this->accountCode, 0, 0, 'L');
        $this->SetFont('Arial', 'B', 8.5);
        $this->Cell(25, 5.5, 'Date Printed:', 0, 0, 'L');
        $this->SetFont('Arial', '', 8.5);
        $this->Cell(0, 5.5, date('d-M-Y H:i'), 0, 1, 'L');

        $this->SetFont('Arial', 'B', 8.5);
        $this->Cell(25, 5.5, 'Account Name:', 0, 0, 'L');
        $this->SetFont('Arial', 'B', 8.5);
        $this->SetTextColor(30, 58, 138);
        $this->Cell(65, 5.5, $this->accountName, 0, 0, 'L');
        $this->SetTextColor(30, 41, 59);
        $this->SetFont('Arial', 'B', 8.5);
        $this->Cell(25, 5.5, 'Period:', 0, 0, 'L');
        $this->SetFont('Arial', '', 8.5);
        $this->Cell(0, 5.5, $this->periodText, 0, 1, 'L');
        $this->Ln(2);

        // Table Header Matching Accounts' Ledgers module
        $this->SetFont('Arial', 'B', 8.5);
        $this->SetFillColor(31, 78, 121);
        $this->SetTextColor(255, 255, 255);
        $this->SetDrawColor(31, 78, 121);

        $this->Cell(20, 6.5, 'Date', 1, 0, 'C', true);
        $this->Cell(20, 6.5, 'Tran. No.', 1, 0, 'C', true);
        $this->Cell(20, 6.5, 'Ref. No.', 1, 0, 'C', true);
        $this->Cell(60, 6.5, 'Description', 1, 0, 'L', true);
        $this->Cell(23, 6.5, 'Debit', 1, 0, 'R', true);
        $this->Cell(23, 6.5, 'Credit', 1, 0, 'R', true);
        $this->Cell(24, 6.5, 'Balance', 1, 1, 'R', true);
    }

    function Footer() {
        $this->SetY(-15);
        $this->SetFont('Arial', 'I', 8);
        $this->SetTextColor(148, 163, 184);
        $this->Cell(0, 10, 'Page ' . $this->PageNo() . ' | Generated by SoftifyX Financials ERP', 0, 0, 'C');
    }
}

function generateLedgerPdf($pdo, $company_id, $coa_id, $type = 'customer', $from_date = null, $to_date = null) {
    // 1. Fetch Company Info
    $stmtComp = $pdo->prepare("SELECT name as company_name, address, phone, email FROM companies WHERE id = ?");
    $stmtComp->execute([$company_id]);
    $comp = $stmtComp->fetch(PDO::FETCH_ASSOC) ?: [
        'company_name' => 'SOFTIFYX FINANCIALS',
        'address' => 'Main Commercial Area',
        'phone' => '',
        'email' => ''
    ];

    // 2. Fetch Account Info
    $stmtAcc = $pdo->prepare("SELECT code, name FROM coa_list WHERE id = ? AND company_id = ?");
    $stmtAcc->execute([$coa_id, $company_id]);
    $acc = $stmtAcc->fetch(PDO::FETCH_ASSOC);
    if (!$acc) {
        throw new Exception("Account not found");
    }

    // 3. Fetch Ledger Transactions using Official Accounts' Ledgers Engine
    $raw_txs = fetchLedgerTransactions($pdo, $company_id, $coa_id, $from_date, $to_date);

    $pdf = new LedgerPDF('P', 'mm', 'A4');
    $pdf->companyName = $comp['company_name'];
    $pdf->companyAddress = $comp['address'] . (!empty($comp['phone']) ? ' | ' . $comp['phone'] : '');
    $pdf->accountName = $acc['name'];
    $pdf->accountCode = $acc['code'];
    $pdf->accountType = strtoupper($type);
    
    if ($from_date && $to_date) {
        $pdf->periodText = date('d-M-Y', strtotime($from_date)) . ' To ' . date('d-M-Y', strtotime($to_date));
    } elseif ($from_date) {
        $pdf->periodText = 'From ' . date('d-M-Y', strtotime($from_date));
    } elseif ($to_date) {
        $pdf->periodText = 'Up to ' . date('d-M-Y', strtotime($to_date));
    } else {
        $pdf->periodText = 'All Dates (Complete Ledger)';
    }

    $pdf->AddPage();
    $pdf->SetAutoPageBreak(true, 18);

    $runningBalance = 0;
    $totalDebit = 0;
    $totalCredit = 0;

    $pdf->SetFont('Arial', '', 8);
    $pdf->SetDrawColor(226, 232, 240);

    $fill = false;
    foreach ($raw_txs as $tx) {
        $db = floatval($tx['debit'] ?? 0);
        $cr = floatval($tx['credit'] ?? 0);
        $isOb = !empty($tx['is_ob']);

        // Skip 0/0 transactions unless it is OB with non-zero or specific from_date
        if (!$isOb && $db == 0 && $cr == 0) {
            continue;
        }

        if ($type === 'customer') {
            $runningBalance += ($db - $cr);
        } else {
            $runningBalance += ($cr - $db);
        }

        if (!$isOb) {
            $totalDebit += $db;
            $totalCredit += $cr;
        } else {
            if ($db > 0) $totalDebit += $db;
            if ($cr > 0) $totalCredit += $cr;
        }

        $pdf->SetFillColor($fill ? 248 : 255, $fill ? 250 : 255, $fill ? 252 : 255);
        if ($isOb) {
            $pdf->SetFillColor(241, 245, 249);
            $pdf->SetFont('Arial', 'B', 8);
        }

        // Date
        $dateDisp = !empty($tx['date']) ? date('d-M-Y', strtotime($tx['date'])) : '';
        $pdf->Cell(20, 6, $dateDisp, 1, 0, 'C', true);

        // Tran. No.
        $tranNo = $tx['tran_no'] ?? ($isOb ? 'OB' : '');
        $pdf->Cell(20, 6, $tranNo, 1, 0, 'C', true);

        // Ref. No.
        $refNo = substr($tx['reference'] ?? '', 0, 12);
        $pdf->Cell(20, 6, $refNo, 1, 0, 'C', true);

        // Description
        $desc = substr($tx['description'] ?? '', 0, 38);
        $pdf->Cell(60, 6, $desc, 1, 0, 'L', true);
        
        // Debit
        if ($db > 0) {
            $pdf->SetTextColor(22, 163, 74);
            $pdf->Cell(23, 6, number_format($db, 2), 1, 0, 'R', true);
        } else {
            $pdf->SetTextColor(148, 163, 184);
            $pdf->Cell(23, 6, '-', 1, 0, 'R', true);
        }

        // Credit
        if ($cr > 0) {
            $pdf->SetTextColor(220, 38, 38);
            $pdf->Cell(23, 6, number_format($cr, 2), 1, 0, 'R', true);
        } else {
            $pdf->SetTextColor(148, 163, 184);
            $pdf->Cell(23, 6, '-', 1, 0, 'R', true);
        }

        // Balance
        $pdf->SetTextColor(30, 41, 59);
        $pdf->SetFont('Arial', 'B', 8);
        $balSign = ($runningBalance >= 0) ? 'Dr' : 'Cr';
        $pdf->Cell(24, 6, number_format(abs($runningBalance), 2) . ' ' . $balSign, 1, 1, 'R', true);
        $pdf->SetFont('Arial', '', 8);

        $fill = !$fill;
    }

    // Totals Row matching Accounts' Ledgers Totals
    $pdf->SetFont('Arial', 'B', 8.5);
    $pdf->SetFillColor(241, 245, 249);
    $pdf->SetTextColor(30, 41, 59);
    $pdf->Cell(120, 7, 'Totals Rs. Summary:', 1, 0, 'R', true);
    
    $pdf->SetTextColor(22, 163, 74);
    $pdf->Cell(23, 7, number_format($totalDebit, 2), 1, 0, 'R', true);
    
    $pdf->SetTextColor(220, 38, 38);
    $pdf->Cell(23, 7, number_format($totalCredit, 2), 1, 0, 'R', true);
    
    $pdf->SetTextColor(30, 58, 138);
    $finalBalSign = ($runningBalance >= 0) ? 'Debit' : 'Credit';
    $pdf->Cell(24, 7, number_format(abs($runningBalance), 2) . ' ' . $finalBalSign, 1, 1, 'R', true);

    // Signature section
    $pdf->Ln(12);
    $pdf->SetFont('Arial', '', 8.5);
    $pdf->SetTextColor(71, 85, 105);
    $pdf->Cell(60, 4, '_____________________', 0, 0, 'C');
    $pdf->Cell(70, 4, '_____________________', 0, 0, 'C');
    $pdf->Cell(60, 4, '_____________________', 0, 1, 'C');
    $pdf->Cell(60, 5, 'Prepared By', 0, 0, 'C');
    $pdf->Cell(70, 5, 'Checked By', 0, 0, 'C');
    $pdf->Cell(60, 5, 'Authorized Signature', 0, 1, 'C');

    // Save to uploads/ledgers
    $uploadDir = dirname(__DIR__) . DIRECTORY_SEPARATOR . 'uploads' . DIRECTORY_SEPARATOR . 'ledgers' . DIRECTORY_SEPARATOR;
    if (!is_dir($uploadDir)) {
        @mkdir($uploadDir, 0777, true);
    }

    $cleanName = preg_replace('/[^a-zA-Z0-9_\-]/', '_', $acc['name']);
    $fileName = 'Ledger_' . $cleanName . '_' . date('Ymd_His') . '.pdf';
    $filePath = $uploadDir . $fileName;

    $pdf->Output('F', $filePath);

    // Public URL
    $isHttps = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') || (isset($_SERVER['SERVER_PORT']) && $_SERVER['SERVER_PORT'] == 443) || (isset($_SERVER['HTTP_X_FORWARDED_PROTO']) && $_SERVER['HTTP_X_FORWARDED_PROTO'] === 'https');
    $protocol = $isHttps ? 'https://' : 'http://';
    $host = $_SERVER['HTTP_HOST'] ?? 'localhost';
    $scriptName = str_replace('\\', '/', $_SERVER['SCRIPT_NAME'] ?? '');
    $webRoot = preg_replace('#/api/.*$#i', '', $scriptName);
    $fileUrl = $protocol . $host . rtrim($webRoot, '/') . '/uploads/ledgers/' . $fileName;

    return [
        'file_path' => $filePath,
        'file_name' => $fileName,
        'file_url' => $fileUrl,
        'total_debit' => $totalDebit,
        'total_credit' => $totalCredit,
        'running_balance' => $runningBalance
    ];
}
